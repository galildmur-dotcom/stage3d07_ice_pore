#!/usr/bin/env python3
"""P10QK: auditable h/q hybrid for one REAL curved M8 parent case.

All h partitions are generated by P10QK_M8_GENERATE_HYBRID_GRADIENT_CHILDREN.py.
Only genuine active 1/2-boundary sub-Tet10 use Algoim/LAPACKE.
Full Tet10 cubic gradient and volume are independently known analytic moments.
The result is an explicit NOT-CERTIFIED scientific diagnostic, never FEM authority.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
import re
import resource
import subprocess

import numpy as np

import P10PX_M8_CONSERVATIVE_TET10_TRIAGE as m8

PREFIX='P10QK_M8_HYBRID_'
RESULT_RE=re.compile(
    r'^P10QK_CUT child=(\d+) q=(\d+) cut_gradient_m3=(\S+) '
    r'cut_volume_m3=(\S+) full_gradient_relative=(\S+) '
    r'full_volume_relative=(\S+) points=(\d+) inside=(\d+) min_weight=(\S+)$')
ORDERS=(2,3,4,6,8)


def rlimit():
    resource.setrlimit(resource.RLIMIT_AS,(1_800_000_000,1_800_000_000))


def check_report(report, inp, requested_h, level, mesh_sha):
    if report['mesh_sha256']!=mesh_sha or report['source_cases']!=[4] or \
       report['h_depth_limit']!=requested_h or report['min_h_one']!=level or \
       report['mesh_changed'] or report['physical_FEM_run']:
        raise ValueError('P10QK_REPORT_PIN_OR_SCOPE_MISMATCH')
    if report['worker_input_sha256']!=hashlib.sha256(inp.read_bytes()).hexdigest():
        raise ValueError('P10QK_TERMINAL_INPUT_SHA_MISMATCH')
    terms=report['terminals'];group=report['cases'][0]['group_counts']
    if len(terms)!=sum(group.get(k,0) for k in ('inside','one','multi')):
        raise ValueError('P10QK_TERMINAL_PARTITION_COUNT_MISMATCH')
    if report['cases'][0]['full_mass_partition_closure']>3e-10:
        raise ValueError('P10QK_NONCONSERVATIVE_H_PARTITION')
    for t in terms:
        status=np.asarray(t['status'])
        if any(v not in (0,1) for v in status):
            raise ValueError('P10QK_OUTSIDE_OR_INVALID_CLASS_IN_TERMINALS')
        n=int(np.count_nonzero(status==0))
        expected='inside' if n==0 else ('one' if n==1 else 'multi')
        if t['group']!=expected or n>2:
            raise ValueError('P10QK_ACTIVE_CLASSIFICATION_BROKEN')
        if t['group']=='one' and t['h_depth']<level:
            raise ValueError('P10QK_ONE_H_DEPTH_NOT_ENFORCED')
        if not t['unknown_cut_gradient_lower_m3']-1e-20 <= \
               t['exact_full_gradient_m3'] <= t['unknown_cut_gradient_upper_m3']+1e-20:
            raise ValueError('P10QK_EXACT_FULL_MOMENT_OUTSIDE_BERNSTEIN')
        if not(t['exact_full_volume_m3']>0):
            raise ValueError('P10QK_NONPOSITIVE_CURVED_TET_VOLUME')
    return terms


def run_worker(binary,inp,index,strategy):
    cmd=[str(binary),str(inp),str(index),'8',strategy]
    try:
        run=subprocess.run(cmd,timeout=20,preexec_fn=rlimit,
                           capture_output=True,text=True,check=False)
    except subprocess.TimeoutExpired:
        return None,'20S_WATCHDOG'
    if run.returncode!=0 or 'P10QK_HYBRID_ONE_OR_TWO_REAL_M8_ALGOIM_PASS' not in run.stdout:
        return None,'EXIT_'+str(run.returncode)+'_'+run.stderr[-200:]
    series={}
    for line in run.stdout.splitlines():
        match=RESULT_RE.fullmatch(line)
        if not match:continue
        child,q,cutg,cutv,eg,ev,n,inside,minw=match.groups()
        if int(child)!=index or int(q) in series:
            return None,'UNEXPECTED_Q_OR_CHILD'
        values={'cut_gradient_m3':float(cutg),'cut_volume_m3':float(cutv),
                'full_gradient_relative':float(eg),'full_volume_relative':float(ev),
                'points':int(n),'inside':int(inside),'min_weight':float(minw)}
        if not all(math.isfinite(v) for v in values.values()) or \
           values['points']>1_000_000 or values['min_weight']<=0:
            return None,'INVALID_WEIGHTS_OR_FINITE_VALUES'
        series[int(q)]=values
    if tuple(sorted(series))!=ORDERS:
        return None,'INCOMPLETE_QUADRATURE_ORDERS'
    return series,None


def audit_partition(report,inp,exe,level,strategy):
    terminals=check_report(report,inp,8,level,m8.PINNED_M8_SHA256)
    data=[];failed=[];cut_by_order={str(q):0. for q in ORDERS}
    exact_inside=0.;l1diff=0.;signeddiff=0.;local_bad=[]
    all_full_poly=True
    unknown_lower=0.;unknown_upper=0.
    one_abs8=0.;multi_abs8=0.;counts={'inside':0,'one':0,'multi':0}
    for i,t in enumerate(terminals):
        group=t['group'];counts[group]+=1
        record={'index':i,'group':group,'h_depth':t['h_depth'],
                'active_indices':[j for j,v in enumerate(t['status']) if v==0],
                'analytic_full_gradient_m3':t['exact_full_gradient_m3']}
        if group=='inside':
            exact_inside+=t['exact_full_gradient_m3']
            record['analytic_inside_gradient_m3']=t['exact_full_gradient_m3']
        else:
            series,err=run_worker(exe,inp,i,strategy)
            if err:
                failed.append({'index':i,'reason':err});record['failure']=err
                unknown_lower+=t['unknown_cut_gradient_lower_m3']
                unknown_upper+=t['unknown_cut_gradient_upper_m3']
            else:
                record['q']=series
                for q in ORDERS:
                    cut_by_order[str(q)]+=series[q]['cut_gradient_m3']
                full_ok=all(series[q]['full_gradient_relative']<=1e-10 and
                            series[q]['full_volume_relative']<=1e-10 for q in ORDERS)
                all_full_poly &= full_ok
                record['analytic_full_polynomial_pass']=full_ok
                g8=series[8]['cut_gradient_m3'];g6=series[6]['cut_gradient_m3']
                delta=g8-g6
                record['q6_q8_absolute_delta_m3']=abs(delta)
                record['q6_q8_relative_delta']=abs(delta)/max(abs(g8),1e-18)
                record['local_cut_q_convergence_pass_1e_minus_6']=(
                    record['q6_q8_relative_delta']<=1e-6)
                if not record['local_cut_q_convergence_pass_1e_minus_6']:
                    local_bad.append(i)
                if group=='one':one_abs8+=abs(g8)
                else:multi_abs8+=abs(g8)
                l1diff+=abs(delta);signeddiff+=delta
                if not t['unknown_cut_gradient_lower_m3']-1e-19 <=g8<= \
                       t['unknown_cut_gradient_upper_m3']+1e-19:
                    raise ValueError('P10QK_Q8_OUTSIDE_BERNSTEIN_INTEGRAL_BOUNDS')
        data.append(record)
    sums={q:exact_inside+g for q,g in cut_by_order.items()}
    denom=max(sum(abs(x['q'][8]['cut_gradient_m3']) for x in data if 'q' in x),1e-25)
    residual=report['cases'][0]['residual_multi_gradient_enclosure_m3']
    if residual[0]<-1e-19 or residual[1]>2.41e-15 or counts['multi']!=5:
        raise ValueError('P10QK_GEOMETRIC_ENCLOSURE_UNEXPECTED_FOR_PINNED_CASE4')
    return {'min_h_one':level,'quadrature_strategy':strategy,'group_counts':counts,
            'source_case':4,'original_element_id':report['cases'][0]['original_element_id'],
            'full_physical_volume_m3':report['cases'][0]['root_volume_m3'],
            'physical_volume_by_class_fraction':report['cases'][0]['group_physical_volume_fraction'],
            'mass_partition_closure':report['cases'][0]['full_mass_partition_closure'],
            'exact_inside_gradient_m3':exact_inside,
            'q_total_gradient_m3_by_order':sums,
            'q6_q8_signed_delta_m3':signeddiff,
            'q6_q8_L1_delta_m3':l1diff,
            'q6_q8_L1_relative':l1diff/denom,
            'q6_q8_signed_relative':abs(signeddiff)/denom,
            'q8_one_L1_m3':one_abs8,'q8_multi_L1_m3':multi_abs8,
            'all_full_polynomial_checks_pass_at_1e_minus_10':all_full_poly,
            'local_cut_q_convergence_failed_indices':local_bad,
            'cut_q_relative_threshold':1e-6,
            'worker_failures':failed,
            'residual_multi_bernstein_enclosure_m3':residual,
            'failed_worker_bernstein_enclosure_m3':[unknown_lower,unknown_upper],
            'not_certified_for_physics':True,
            'terminals':data}


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--mesh',type=Path,required=True)
    p.add_argument('--source',type=Path,default=Path('P10QK_M8_HYBRID_ONE_OR_TWO_CUT_ALGOIM.cpp'))
    p.add_argument('--binary',type=Path,default=Path('p10qk_m8_hybrid_algoim_pilot'))
    p.add_argument('--output',type=Path,default=Path('P10QK_M8_HYBRID_H_AND_Q_INDEPENDENT_QA.json'))
    p.add_argument('--levels',type=int,nargs='+',default=[0,4,6,8])
    p.add_argument('--strategy',choices=['auto','gl'],default='auto')
    a=p.parse_args()
    sha=hashlib.sha256(a.mesh.read_bytes()).hexdigest()
    if sha!=m8.PINNED_M8_SHA256 or a.levels!=sorted(set(a.levels)) or \
       not all(0<=x<=8 for x in a.levels):
        raise ValueError('P10QK_WRONG_INPUT_M8_OR_LEVELS')
    if not a.source.exists() or not a.binary.exists():
        raise ValueError('P10QK_WORKER_SOURCE_OR_EXECUTABLE_MISSING')
    partitions=[]
    for level in a.levels:
        stem='CASE4_H8'+('' if level==0 else '_ONE'+str(level))
        j=Path(PREFIX+'CHILDREN_'+stem+'_QA.json')
        inp=Path(PREFIX+'GRADIENT_'+stem+'_INPUT.txt')
        report=json.loads(j.read_text())
        out=audit_partition(report,inp,a.binary.resolve(),level,a.strategy)
        partitions.append(out)
        print('P10QK_H_Q_RESULT min_h_one=',level,
              'cuts=',out['group_counts']['one']+out['group_counts']['multi'],
              'L1_6_8=',format(out['q6_q8_L1_relative'],'.9g'),
              'nonconv=',len(out['local_cut_q_convergence_failed_indices']),
              'failures=',len(out['worker_failures']),flush=True,sep='')
    cross=[]
    for left,right in zip(partitions,partitions[1:]):
        x=left['q_total_gradient_m3_by_order']['8']
        y=right['q_total_gradient_m3_by_order']['8']
        cross.append({'min_h_one_left':left['min_h_one'],
                      'min_h_one_right':right['min_h_one'],
                      'q8_signed_total_shift_m3':y-x,
                      'q8_signed_total_shift_relative':abs(y-x)/max(abs(y),1e-25)})
    result={'stage':'P10QK','scope':'real M8 source-case 4 / full curved child / h<=8',
            'quadrature_strategy':a.strategy,
            'mesh_sha256':sha,'source_sha256':hashlib.sha256(a.source.read_bytes()).hexdigest(),
            'physical_FEM_executed':False,'CAD_executed':False,'Gmsh_executed':False,
            'high_order_elastic_policy':'mandatory for any FUTURE Gmsh mesh optimization',
            'algorithm':'exact cubic full FE numerator, Bernstein physical classification, '
                        'exact inside, genuine Algoim/LAPACKE on active one/two',
            'numeric_status':'NO_CERTIFICATION_FOR_PHYSICAL_4D_FEM',
            'q6_q8_empirical_delta_is_not_a_rigorous_error_bound':True,
            'bernstein_bound_has_floating_margin_not_directed_rounding':True,
            'partitions':partitions,'cross_h_q8_signed_comparison':cross,
            'physical_4D_FEM_approved':False}
    a.output.write_text(json.dumps(result,indent=2)+'\n')
    print('P10QK_INDEPENDENT_H_AND_Q_AUDIT_COMPLETE_PHYSICS_NOT_CERTIFIED',flush=True)


if __name__=='__main__':
    main()
